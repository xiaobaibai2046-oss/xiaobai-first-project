河姆渡与半坡的比较|河姆渡居民主要种植水稻，半坡居民主要种植粟，房屋形态等也有差别。比较时把自然环境、生产和生活联系起来。
夏朝与世袭制|传统历史叙述中，夏朝建立后王位世袭制逐步代替禅让制，体现早期国家发展。不能把传说叙述与考古证据无条件等同。
商代甲骨文|甲骨文刻写于龟甲、兽骨等，记录占卜及相关事项，是研究商代历史的重要材料。中国有文字可考的历史通常从商朝算起。
